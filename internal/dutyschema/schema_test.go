func open(t *testing.T) *gorm.DB {
	t.Helper()
	db, e := gorm.Open(sqlite.Open(filepath.Join(t.TempDir(), "test.db")), &gorm.Config{Logger: logger.Default.LogMode(logger.Silent)})
	if e != nil {
		t.Fatal(e)
	}
	conn, _ := db.DB()
	t.Cleanup(func() { conn.Close() })
	return db
}
func apply(t *testing.T, db *gorm.DB, sql string) {
	t.Helper()
	if e := db.Exec(sql).Error; e != nil {
		t.Fatal(e)
	}
}
func tables() []interface{} { return append(models.DutySchemaModels(), &migrate.NotifyRule{}) }
func shape(t *testing.T, db *gorm.DB, model interface{}) []map[string]interface{} {
	t.Helper()
	s, e := schema.Parse(model, &sync.Map{}, schema.NamingStrategy{})
	if e != nil {
		t.Fatal(e)
	}
	var rows []map[string]interface{}
	if e = db.Raw("PRAGMA table_info('" + s.Table + "')").Scan(&rows).Error; e != nil {
		t.Fatal(e)
	}
	return rows
}
func TestSQLiteInitializerMatchesRuntime(t *testing.T) {
	db := open(t)
	raw, e := os.ReadFile("../../docker/sqlite.sql")
	if e != nil {
		t.Fatal(e)
	}
	apply(t, db, string(raw))
	expected := open(t)
	if e = expected.AutoMigrate(tables()...); e != nil {
		t.Fatal(e)
	}
	for _, model := range tables() {
		if !reflect.DeepEqual(shape(t, db, model), shape(t, expected, model)) {
			t.Fatalf("column drift %T", model)
		}
		s, _ := schema.Parse(model, &sync.Map{}, schema.NamingStrategy{})
		for name := range s.ParseIndexes() {
			if !db.Migrator().HasIndex(model, name) {
				t.Fatalf("missing index %s", name)
			}
		}
	}
	// Re-running startup migration must preserve initial data and require no new custom DDL.
	var count int64
	db.Table("users").Count(&count)
	if count == 0 {
		t.Fatal("upstream seed users missing")
	}
	if e = models.InitDutySchema(db, filepath.Join(t.TempDir(), "key")); e != nil {
		t.Fatal(e)
	}
	if e = db.AutoMigrate(&migrate.NotifyRule{}); e != nil {
		t.Fatal(e)
	}
	for _, model := range tables() {
		if !reflect.DeepEqual(shape(t, db, model), shape(t, expected, model)) {
			t.Fatalf("startup changed columns %T", model)
		}
	}
}
func TestGeneratedDialectsAreCurrent(t *testing.T) {
	for dialect, path := range map[string]string{"sqlite": "../../docker/sqlite.sql", "mysql": "../../docker/initsql/a-n9e.sql", "postgres": "../../docker/compose-postgres/initsql_for_postgres/a-n9e-for-Postgres.sql"} {
		t.Run(dialect, func(t *testing.T) {
			raw, e := os.ReadFile(path)
			if e != nil {
				t.Fatal(e)
			}
			notify, e := Render(dialect, true)
			if e != nil {
				t.Fatal(e)
			}
			duty, e := Render(dialect, false)
			if e != nil {
				t.Fatal(e)
			}
			want := "-- BEGIN GENERATED DUTY SCHEMA\n-- Generated by go run ./cmd/duty-schema; do not edit this block.\n" + notify + duty + "-- END GENERATED DUTY SCHEMA\n"
			if !strings.HasSuffix(string(raw), want) {
				t.Fatal("SQL drift: run go run ./cmd/duty-schema")
			}
		})
	}
}
func TestExistingCustomDatabaseUpgradePreservesRows(t *testing.T) {
	db := open(t)
	ddl, e := Render("sqlite", false)
	if e != nil {
		t.Fatal(e)
	}
	// Earlier custom builds lacked assignment_version and claim_notice.group_id.
	ddl = strings.ReplaceAll(ddl, "`assignment_version` integer,", "")
	ddl = strings.Replace(ddl, "CREATE TABLE `response_claim_notice` (`group_id` integer,", "CREATE TABLE `response_claim_notice` (", 1)
	apply(t, db, ddl)
	apply(t, db, "INSERT INTO response_event (id,episode,owner_id,version) VALUES(1,'old:100',42,7)")
	apply(t, db, "INSERT INTO response_claim_notice (id,dedup_key,status) VALUES(1,'old-job','sent')")
	key := filepath.Join(t.TempDir(), "key")
	for i := 0; i < 2; i++ {
		if e = models.InitDutySchema(db, key); e != nil {
			t.Fatal(e)
		}
	}
	var row models.EventResponse
	if e = db.First(&row, 1).Error; e != nil {
		t.Fatal(e)
	}
	if row.OwnerID != 42 || row.Version != 7 {
		t.Fatal("existing ownership overwritten")
	}
	var notice models.ClaimNotice
	if e = db.First(&notice, 1).Error; e != nil {
		t.Fatal(e)
	}
	if notice.Status != "sent" || notice.DedupKey != "old-job" {
		t.Fatal("existing notice overwritten")
	}
	if !db.Migrator().HasColumn(&models.EventResponse{}, "assignment_version") || !db.Migrator().HasColumn(&models.ClaimNotice{}, "group_id") {
		t.Fatal("missing upgrade columns")
	}
}

func TestUpstreamSQLUpgradePreservesRule(t *testing.T) {
	db := open(t)
	ddl, err := Render("sqlite", true)
	if err != nil {
		t.Fatal(err)
	}
	ddl = strings.ReplaceAll(ddl, "`receiver_mode` varchar(20) DEFAULT \"original\",", "")
	ddl = strings.ReplaceAll(ddl, "`duty_group_id` integer DEFAULT 0,", "")
	apply(t, db, ddl)
	apply(t, db, "INSERT INTO notify_rule(id,name,enable,notify_configs) VALUES(1,'existing',1,'[]')")
	sql, err := os.ReadFile("../../docker/migratesql/custom/001-duty-sqlite.sql")
	if err != nil {
		t.Fatal(err)
	}
	apply(t, db, string(sql))
	var mode string
	var group int64
	db.Raw("SELECT receiver_mode FROM notify_rule WHERE id=1").Scan(&mode)
	db.Raw("SELECT duty_group_id FROM notify_rule WHERE id=1").Scan(&group)
	if mode != "original" || group != 0 {
		t.Fatalf("wrong defaults %q %d", mode, group)
	}
	var name string
	db.Raw("SELECT name FROM notify_rule WHERE id=1").Scan(&name)
	if name != "existing" {
		t.Fatal("rule lost")
	}
	if err = db.AutoMigrate(&migrate.NotifyRule{}); err != nil {
		t.Fatal(err)
	}
	if err = models.InitDutySchema(db, filepath.Join(t.TempDir(), "key")); err != nil {
		t.Fatal(err)
	}
}
