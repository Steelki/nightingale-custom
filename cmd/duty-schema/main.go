// Generate SQL for duty/response tables; run from the backend repository root.
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/ccfos/nightingale/v6/internal/dutyschema"
)

const marker = "-- BEGIN GENERATED DUTY SCHEMA"

func main() {
	check := flag.Bool("check", false, "fail when checked-in SQL differs from models")
	flag.Parse()
	for _, entry := range []struct{ dialect, path string }{
		{"sqlite", "docker/sqlite.sql"},
		{"mysql", "docker/initsql/a-n9e.sql"},
		{"postgres", "docker/compose-postgres/initsql_for_postgres/a-n9e-for-Postgres.sql"},
	} {
		raw, err := os.ReadFile(entry.path)
		must(err)
		base := strings.Split(string(raw), marker)[0]
		// Replace existing notify_rule definition with current migration model.
		name := "notify_rule"
		if entry.dialect != "postgres" {
			name = "`notify_rule`"
		}
		start := strings.Index(base, "CREATE TABLE "+name+" (")
		if start >= 0 {
			end := strings.Index(base[start:], ";")
			if end < 0 {
				panic("unterminated notify_rule table")
			}
			base = base[:start] + base[start+end+1:]
		}
		notify, err := dutyschema.Render(entry.dialect, true)
		must(err)
		duty, err := dutyschema.Render(entry.dialect, false)
		must(err)
		content := strings.TrimSpace(base) + "\n\n" + marker + "\n-- Generated by go run ./cmd/duty-schema; do not edit this block.\n" + notify + duty + "-- END GENERATED DUTY SCHEMA\n"
		write(entry.path, content, *check)
		// A versioned, one-time upgrade from upstream v9.3.0, not a re-runnable initializer.
		upgrade := "-- 001: upstream v9.3.0 -> custom duty schema. Back up first.\n-- Run once only; existing custom installations use runtime AutoMigrate.\n"
		upgrade += "-- Requires a fully initialized upstream database with notify_rule present.\n"
		upgrade += "ALTER TABLE notify_rule ADD COLUMN receiver_mode varchar(20) DEFAULT 'original';\nALTER TABLE notify_rule ADD COLUMN duty_group_id bigint DEFAULT 0;\n"

		upgrade += duty
		// Released upgrade scripts are immutable; future changes get a new version.
		upgradePath := "docker/migratesql/custom/001-duty-" + entry.dialect + ".sql"
		if _, err := os.Stat(upgradePath); os.IsNotExist(err) {
			write(upgradePath, upgrade, *check)
		} else {
			must(err)
		}
	}
}
func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func write(path, content string, check bool) {
	if check {
		old, err := os.ReadFile(path)
		must(err)
		if string(old) != content {
			must(fmt.Errorf("%s is stale; run go run ./cmd/duty-schema", path))
		}
		return
	}
	must(os.WriteFile(path, []byte(content), 0644))
}
